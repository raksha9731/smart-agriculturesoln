document.addEventListener("DOMContentLoaded", function () {
    const calculateButton = document.getElementById("calculateFertilizer");

    if (!calculateButton) return;

    calculateButton.addEventListener("click", function () {
        const crop = document.getElementById("fertCrop").value;
        const n = Number(document.getElementById("nitrogen").value);
        const p = Number(document.getElementById("phosphorus").value);
        const k = Number(document.getElementById("potassium").value);
        const ph = Number(document.getElementById("soilPH").value);

        const result = document.getElementById("fertilizerResult");
        const advice = document.getElementById("fertilizerAdvice");

        if (!crop || !document.getElementById("nitrogen").value ||
            !document.getElementById("phosphorus").value ||
            !document.getElementById("potassium").value ||
            !document.getElementById("soilPH").value) {
            alert("Please enter all values.");
            return;
        }

        if (n < 0 || p < 0 || k < 0 || ph < 0 || ph > 14) {
            alert("Please enter valid soil values.");
            return;
        }

        let message = "Crop selected: " + crop.toUpperCase() + ". ";

        message += "Entered NPK values: N = " + n +
            ", P = " + p + ", K = " + k + ". ";

        if (ph < 5.5) {
            message += "Soil is strongly acidic. Consult a soil expert for suitable soil correction.";
        } else if (ph < 6.5) {
            message += "Soil is mildly acidic. Check crop-specific pH requirements.";
        } else if (ph <= 7.5) {
            message += "Soil pH is near neutral. Check crop-specific requirements.";
        } else {
            message += "Soil is alkaline. Consult an agricultural expert for soil management.";
        }

        message += " NPK values need laboratory interpretation before fertilizer dosage can be recommended.";

        advice.textContent = message;
        result.hidden = false;
    });
});

document.addEventListener("DOMContentLoaded", function () {
    const button = document.getElementById("checkCropHealth");

    if (!button) return;

    button.addEventListener("click", function () {
        const soilPH = document.getElementById("soilPH").value;
        const pest = document.getElementById("pest").value;

        const soilStatus = document.getElementById("soilHealthStatus");
        const irrigationStatus = document.getElementById("irrigationStatus");
        const pestStatus = document.getElementById("pestHealthStatus");

        if (soilPH === "") {
            soilStatus.textContent = "Not Checked";
        } else if (Number(soilPH) >= 6 && Number(soilPH) <= 7.5) {
            soilStatus.textContent = "Near Neutral";
        } else {
            soilStatus.textContent = "Needs Review";
        }

        irrigationStatus.textContent =
            "Check soil moisture before watering";

        pestStatus.textContent =
            pest ? "Pest Selected: " + pest : "No Pest Selected";

        const summary = document.getElementById("cropHealthSummary");

        summary.textContent =
            "Soil pH: " + soilStatus.textContent +
            " | Irrigation: " + irrigationStatus.textContent +
            " | Pest Monitoring: " + pestStatus.textContent +
            ". These are basic indicators, not a scientific crop diagnosis.";

        document.getElementById("cropHealthResult").hidden = false;
    });
});
