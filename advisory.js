const advisoryForm = document.getElementById("advisoryForm");

advisoryForm.addEventListener("submit", function(event) {
    event.preventDefault();

    const crop = document.getElementById("crop").value;
    const pest = document.getElementById("pest").value;
    const location = document.getElementById("location").value;
    const stage = document.getElementById("stage").value;

    let observation = "";
    let guidance = "";

const cropData = advisoryDatabase[crop];

if (cropData && cropData.guidance[pest]) {
    guidance = cropData.guidance[pest];
} else {
    guidance = "Please consult a local agricultural expert for crop-specific pest identification.";
}

    // General guidance based on observed symptoms
    switch (pest) {
        case "chewing":
            observation = "Leaf damage or holes observed";
            guidance = "Inspect leaves for caterpillars or other chewing insects. Check both sides of leaves and remove affected parts where appropriate.";
            break;

        case "sucking":
            observation = "Possible sucking insect activity";
            guidance = "Inspect leaves for aphids, whiteflies or other small insects. Check whether leaves are curling or sticky.";
            break;

        case "spots":
            observation = "Leaf spots or discoloration";
            guidance = "Spots may result from disease, pests, nutrient issues or environmental stress. Avoid assuming that an insecticide is required.";
            break;

        case "wilting":
            observation = "Wilting or drying";
            guidance = "Check soil moisture, drainage, roots and plant stems. Wilting can have several causes and may not be related to pests.";
            break;

        default:
            observation = "Pest not identified";
            guidance = "Take clear photographs of the affected plant and consult a local agricultural expert for identification.";
    }

    const result = document.getElementById("advisoryResult");

    result.innerHTML = `
        <h2>🌱 Advisory Result</h2>

        <p><strong>Crop:</strong> ${crop}</p>
        <p><strong>Location:</strong> ${escapeHTML(location)}</p>
        <p><strong>Growth Stage:</strong> ${stage}</p>
        <p><strong>Observation:</strong> ${observation}</p>

        <h3>Recommended Next Steps</h3>
        <p>${guidance}</p>

        <h3>🛡️ Safety Guidance</h3>
        <ul>
            <li>Confirm the pest before choosing a pesticide.</li>
            <li>Prefer suitable non-chemical control methods when possible.</li>
            <li>Use only products registered for the specific crop and pest.</li>
            <li>Follow the approved product label for dosage and precautions.</li>
            <li>Consult a KVK or agricultural officer before chemical application.</li>
        </ul>

        <p class="result-disclaimer">
            No chemical dosage is generated by this prototype.
        </p>
    `;

    result.hidden = false;
    result.scrollIntoView({ behavior: "smooth" });
});

function escapeHTML(value) {
    return value.replace(/[&<>"']/g, function(character) {
        return {
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#39;"
        }[character];
    });
}


const pestImageInput = document.getElementById("pestImage");
const previewImage = document.getElementById("previewImage");
const previewMessage = document.getElementById("previewMessage");

pestImageInput.addEventListener("change", function () {
    const file = this.files[0];

    if (!file) {
        previewImage.hidden = true;
        previewMessage.textContent = "Your uploaded image will appear here.";
        return;
    }

    if (!file.type.startsWith("image/")) {
        alert("Please select an image file.");
        this.value = "";
        return;
    }

    const imageURL = URL.createObjectURL(file);

    previewImage.src = imageURL;
    previewImage.hidden = false;
    previewMessage.textContent = "Image uploaded successfully!";
});


